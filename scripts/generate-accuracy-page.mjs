// ---------------------------------------------------------------- helpers

const esc = (s) =>
  String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

/**
 * VitePress compiles markdown as a Vue SFC, so `{{` in raw HTML would be parsed as an
 * interpolation and either render wrong or fail the build. Extraction output is arbitrary
 * model text and can contain anything, so every interpolated string goes through this.
 */
const safe = (s) => esc(s).replaceAll("{{", "&#123;&#123;").replaceAll("}}", "&#125;&#125;");

const pct = (n) => (n == null ? "n/a" : (100 * n).toFixed(1));

/**
 * Derive a plain-English row label from a dotted leaf path.
 *
 * Strip the group prefix from the leaf name (case-insensitively, only when the remainder
 * is non-empty), then de-camel-case and sentence-case. Fall back to the full de-camel-cased
 * leaf name when the prefix doesn't match.
 *
 *   attic.atticInsulationDepth → "Insulation depth"
 *   health.healthGasLeak       → "Gas leak"
 *   basedata.yearBuilt         → "Year built"
 */
function leafLabel(path) {
  const dot = path.indexOf(".");
  if (dot < 0) return sentenceCase(deCamel(path));
  const group = path.slice(0, dot);
  const leaf = path.slice(dot + 1);
  if (leaf.length > group.length && leaf.toLowerCase().startsWith(group.toLowerCase())) {
    return sentenceCase(deCamel(leaf.slice(group.length)));
  }
  return sentenceCase(deCamel(leaf));
}

/** Insert spaces at camelCase boundaries and before digits that follow letters. */
function deCamel(s) {
  return s
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([a-zA-Z])(\d)/g, "$1 $2")
    .replace(/(\d)([A-Z])/g, "$1 $2");
}

/** Capitalise the first letter, lower-case the rest. */
function sentenceCase(s) {
  return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
}

/** The case ids the grid carries, sorted — the page's columns. */
function caseIdsOf(run) {
  const ids = new Set();
  for (const col of Object.values(run.grid)) {
    for (const id of Object.keys(col)) ids.add(id);
  }
  return [...ids].sort();
}

/**
 * Fail loudly rather than render a partial page. The record itself is zod-parsed by
 * `readEvalRunRecords`; this checks the one cross-field rule the schema cannot carry: the
 * grid is dense — exactly the leaves of `leafPaths`, exactly the same cases in every column.
 */
function requireDenseGrid(run, name) {
  const ids = caseIdsOf(run);
  const paths = Object.keys(run.grid);
  if (paths.length !== run.leafPaths.length || !run.leafPaths.every((p) => p in run.grid)) {
    throw new Error(
      `${name}: the grid is keyed by ${paths.length} leaves but the record names ` +
        `${run.leafPaths.length} leaf paths — the grid is dense by contract, never sparse.`,
    );
  }
  for (const path of run.leafPaths) {
    for (const id of ids) {
      if (!(id in run.grid[path])) {
        throw new Error(
          `${name}: the grid has no cell for leaf "${path}", case "${id}" — the grid is ` +
            `dense by contract, never sparse.`,
        );
      }
    }
  }
}

/**
 * Per-bucket tally over a record's grid. Every read goes through `bucketOf`, so an
 * out-of-vocabulary verdict throws here rather than silently dropping out of the counts.
 */
export function bucketCounts(run) {
  const counts = {};
  for (const path of run.leafPaths) {
    const col = run.grid[path] ?? {};
    for (const id of Object.keys(col)) {
      const b = bucketOf(col[id]);
      counts[b] = (counts[b] ?? 0) + 1;
    }
  }
  return counts;
}

/** The run's settings, as one plain-English line: what was run, not a freshness key. */
function settingsSummary(s) {
  const parts = [s.strategies.join(" → ")];
  if (s.consensusCandidates != null) {
    parts.push(`consensus ×${s.consensusCandidates} (${s.consensusArbiter ?? "unanimous"})`);
  }
  if (s.maxRetries != null) parts.push(`${s.maxRetries} retries per call`);
  if (s.responseCap != null) parts.push(`cap ${s.responseCap} tokens`);
  if (s.splitCaps != null) {
    parts.push(
      `split caps: ${s.splitCaps.maxNullableUnionsPerGroup ?? "—"} nullables, ` +
        `${s.splitCaps.maxSerializedCharsPerGroup ?? "—"} chars`,
    );
  }
  return parts.join(" · ");
}

// ---------------------------------------------------------------- history line

/**
 * A text line below n=2 points. At n=1 it is a stated sentence; at n=2 a comparison;
 * at n>=3 the sparkline returns plus the sentence in words.
 */
function historyLine(values, label) {
  const n = values.length;
  if (n <= 1) {
    return `<p class="ar-hist ar-hist-none">Run 1 of 1 &mdash; no history to compare against yet</p>`;
  }
  if (n === 2) {
    const prev = pct(values[0]);
    const now = pct(values[1]);
    return `<p class="ar-hist">Run 2 of 2 &mdash; previous ${prev}%, now ${now}%</p>`;
  }
  // n >= 3: sparkline + text
  const yMax = Math.max(0.02, Math.ceil(125 * Math.max(...values)) / 100);
  const y = (v) => (30 - 26 * (v / yMax)).toFixed(1);
  const x = (i) => (4 + (124 * i) / (n - 1)).toFixed(1);
  const pts = values.map((v, i) => `${x(i)},${y(v)}`).join(" ");
  const dots =
    n <= 8
      ? values
          .map(
            (v, i) =>
              `<circle class="ar-spark-dot${i === n - 1 ? "" : "-past"}" cx="${x(i)}" cy="${y(v)}" r="${i === n - 1 ? 2.5 : 1.5}"/>`,
          )
          .join("")
      : `<circle class="ar-spark-dot" cx="${x(n - 1)}" cy="${y(values[n - 1])}" r="2.5"/>`;
  const lo = pct(Math.min(...values));
  const hi = pct(Math.max(...values));
  const last = pct(values[n - 1]);
  const aria = `${label} over ${n} runs, ${lo}% to ${hi}%, latest ${last}%`;
  return (
    `<svg class="ar-spark" viewBox="0 0 132 34" width="132" height="34" role="img" aria-label="${esc(aria)}">` +
    `<line class="ar-spark-base" x1="4" y1="30.5" x2="128" y2="30.5"/>` +
    `<polyline class="ar-spark-line" points="${pts}"/>${dots}</svg>\n` +
    `<p class="ar-hist">${n} runs &middot; ${lo}%&ndash;${hi}% &middot; latest ${last}%</p>`
  );
}

