// ---------------------------------------------------------------- helpers

const esc = (s) =>
  String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

/**
 * VitePress compiles markdown as a Vue SFC, so `{{` in raw HTML would be parsed as an
 * interpolation and either render wrong or fail the build. Extraction output is arbitrary
 * model text and can contain anything, so every interpolated string goes through this.
 */
const safe = (s) => esc(s).replaceAll("{{", "&#123;&#123;").replaceAll("}}", "&#125;&#125;");

const pct = (n) => `${(100 * n).toFixed(1)}`;

/**
 * Derive a plain-English row label from a dotted leaf path.
 *
 * Strip the group prefix from the leaf name (case-insensitively, only when the remainder
 * is non-empty), then de-camel-case and sentence-case. Fall back to the full de-camel-cased
 * leaf name when the prefix doesn't match.
 *
 *   attic.atticInsulationDepth → "Insulation depth"
 *   health.healthGasLeak       → "Gas leak"
 *   basedata.yearBuilt         → "Year built"
 *   hvac.hvacHeatingEnergySource → "Heating energy source"
 *   dhw.dhwType2               → "Type 2"
 */
function leafLabel(path) {
  const dot = path.indexOf(".");
  if (dot < 0) return sentenceCase(deCamel(path));
  const group = path.slice(0, dot);
  const leaf = path.slice(dot + 1);
  if (leaf.length > group.length && leaf.toLowerCase().startsWith(group.toLowerCase())) {
    return sentenceCase(deCamel(leaf.slice(group.length)));
  }
  return sentenceCase(deCamel(leaf));
}

/** Insert spaces at camelCase boundaries and before digits that follow letters. */
function deCamel(s) {
  return s
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/([a-zA-Z])(\d)/g, "$1 $2")
    .replace(/(\d)([A-Z])/g, "$1 $2");
}

/** Capitalise the first letter, lower-case the rest. */
function sentenceCase(s) {
  return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
}

/** Fail loudly rather than render a partial page. See the file header. */
function requireShape(run, file) {
  for (const key of [
    "capturedAt",
    "backendLabel",
    "model",
    "passed",
    "hallRate",
    "missRate",
    "hazards",
    "shapeConformance",
    "totals",
    "leafPaths",
    "transcripts",
    "grid",
  ]) {
    if (run[key] === undefined) {
      throw new Error(
        `${file} is missing "${key}". The run-record format changed without this generator ` +
          `being updated — regenerate the run, or fix scripts/generate-accuracy-page.mjs.`,
      );
    }
  }
  const cells = Object.values(run.grid).reduce((n, col) => n + Object.keys(col).length, 0);
  const expected = run.leafPaths.length * run.transcripts.length;
  if (cells !== expected) {
    throw new Error(
      `${file} grid is not dense: ${cells} cells, expected ${expected} ` +
        `(${run.leafPaths.length} leaves x ${run.transcripts.length} transcripts).`,
    );
  }
}

function readRuns() {
  if (!existsSync(RUNS)) return [];
  const out = [];
  for (const f of readdirSync(RUNS).sort()) {
    if (!f.startsWith("current-") || !f.endsWith(".json")) continue;
    const label = f.slice("current-".length, -".json".length);
    const run = JSON.parse(readFileSync(join(RUNS, f), "utf8"));
    requireShape(run, f);
    const hp = join(RUNS, `history-${label}.jsonl`);
    const history = existsSync(hp)
      ? readFileSync(hp, "utf8")
          .split("\n")
          .filter((l) => l.trim() !== "")
          .map((l) => JSON.parse(l))
      : [];
    out.push({ label, run, history });
  }
  return out;
}

function currentFingerprint() {
  if (!existsSync(FIXTURE)) return "";
  return `sha256:${createHash("sha256").update(readFileSync(FIXTURE, "utf8")).digest("hex")}`;
}

