/**
 * A blank or whitespace-only line inside an HTML block ends that block as far as
 * markdown-it is concerned. Everything after it is re-parsed as markdown, indented lines
 * become code blocks, and the enclosing tags never match — Vue's SFC compiler then fails
 * the build with a bare "Element is missing end tag" pointing at a tag that is, in fact,
 * perfectly balanced. That error names a symptom several hundred lines from the cause,
 * which is why this checks the real invariant at the point it is violated.
 */
function assertNoBlankLines(html, label) {
  const lines = html.split("\n");
  for (const [i, line] of lines.entries()) {
    if (line.trim() === "") {
      throw new Error(
        `generate-accuracy-page: emitted a blank line at line ${i + 1} of the "${label}" ` +
          `block. Nothing inside <div class="ar"> may be blank or whitespace-only — it ` +
          `silently terminates the HTML block and breaks the VitePress build. Build the ` +
          `offending section as a filtered array of lines rather than a template with an ` +
          `empty conditional branch.`,
      );
    }
  }
}

function main() {
  const backends = readRuns();
  mkdirSync(dirname(OUT), { recursive: true });

  if (backends.length === 0) {
    writeFileSync(
      OUT,
      `${PREAMBLE}**No accuracy runs have been published yet.** Run the manual acceptance gate to
produce one — see \`packages/ribo-adapter-snuggpro/acceptance/README.md\`.
`,
    );
    console.log(`[accuracy] no runs found in ${RUNS} — wrote the empty-state page`);
    return;
  }

  const fingerprint = currentFingerprint();
  const sections = backends.map(({ label, run, history }) => {
    const { found, index } = collectProblems(run);
    const counts = {};
    for (const col of Object.values(run.grid)) {
      for (const cell of Object.values(col)) {
        const b = BUCKET[cell.verdict] ?? "excused";
        counts[b] = (counts[b] ?? 0) + 1;
      }
    }
    const stale = fingerprint !== "" && run.schemaFingerprint !== fingerprint;
    // Joined with a SINGLE newline, never a blank line. A blank line inside an HTML block
    // ends that block as far as markdown-it is concerned, so the outer `<div class="ar">`
    // would never be matched by its `</div>` and Vue's SFC compiler fails the build with
    // "Element is missing end tag". Blank lines are only safe BETWEEN backends, where each
    // div is already closed.
    const body = [
      `<div class="ar">`,
      staleBanner(stale),
      intro(run),
      workedExample(run),
      finding(run, counts),
      rates(run, history),
      gates(run),
      legend(counts),
      grid(run, index),
      problems(found),
      method(run),
      `</div>`,
    ]
      .filter((s) => s !== "")
      .join("\n");
    assertNoBlankLines(body, label);
    return backends.length > 1 ? `## ${esc(label)}\n\n${body}` : body;
  });

  writeFileSync(OUT, `${PREAMBLE}${sections.join("\n\n")}\n\n<style>\n${STYLE}</style>\n`);
  console.log(
    `[accuracy] wrote ${OUT} from ${backends.length} backend(s): ${backends.map((b) => b.label).join(", ")}`,
  );
}

main();
