/**
 * Three real slots, one per outcome, read from the run record. The "wrong or invented" row has a
 * real source span and extracted value; the "found it" and "missed it" rows use the field
 * name and case id (the record does not store quotes or values for correct or missed
 * cells). Nothing is invented.
 */
export function workedExample(run) {
  const counts = bucketCounts(run);
  const nCases = caseIdsOf(run).length;
  const nCaptured = counts.captured ?? 0;
  const nShort = counts.short ?? 0;
  const nFault = counts.fault ?? 0;

  // Pick one real cell per outcome.
  const found = pickCell(run, "captured");
  const missed = pickCell(run, "short");
  const madeUp = pickCell(run, "fault");

  // Filtered, like the problems list's rows: an outcome the run never produced has no real
  // cell to show, its row renders "", and a "" in the join is the blank line
  // assertNoBlankLines refuses.
  const rows = [
    egFoundRow(found, nCaptured),
    egMissedRow(missed, nShort),
    egMadeUpRow(madeUp, nFault),
  ].filter((row) => row !== "");

  return `<section class="ar-example" aria-labelledby="eg-h">
  <h2 class="ar-h" id="eg-h">Three real slots, to show what is being counted</h2>
  <p class="ar-sub">
    A <dfn class="ar-dfn">slot</dfn> is one field on one capture. ${run.leafPaths.length} &times;
    ${nCases} = ${run.leafPaths.length * nCases} slots. Every slot gets one of these outcomes.
  </p>
  <ol class="ar-eg-list">
${rows.join("\n")}
  </ol>
  <p class="ar-sub">
    There is a fourth, much commoner outcome: the auditor never mentioned a field and the model
    correctly left it blank &mdash; <b>nothing to find</b>, ${counts.absent ?? 0} slots. It counts as correct, but
    it is weaker evidence than <b>found it</b>, so this page never mixes the two. A model that
    returned an entirely blank form would score ${run.leafPaths.length * nCases} of those and would show up here as
    a completely empty grid.
  </p>
</section>`;
}

/**
 * Find a cell matching a bucket, preferring cells with richer data (sourceSpan above
 * all, then expected, got, reason) so the worked example is as concrete as the run
 * record allows.
 */
function pickCell(run, bucket) {
  let best = null;
  let bestScore = -1;
  for (const path of run.leafPaths) {
    for (const id of caseIdsOf(run)) {
      const cell = run.grid[path]?.[id];
      if (!cell || bucketOf(cell) !== bucket) continue;
      let score = 0;
      if (cell.sourceSpan != null) score += 3;
      if (cell.expected != null) score++;
      if (cell.got != null) score++;
      if (cell.reason != null) score++;
      if (score > bestScore) {
        bestScore = score;
        best = { path, id, cell };
      }
    }
  }
  return best;
}

function egFoundRow(c, nCaptured) {
  if (!c) return "";
  const label = leafLabel(c.path);
  return `    <li class="ar-eg ar-eg-ok">
      <p class="ar-eg-wrote">
        <span class="ar-eg-lbl">The model wrote</span>
        <span class="ar-eg-field">${safe(label)}</span>
        in <code>${safe(c.id)}</code>
      </p>
      <p class="ar-eg-verdict">
        <span class="ar-c ar-captured ar-eg-swatch" aria-hidden="true"></span>
        <b>Found it.</b> Stated in the recording, captured correctly. ${nCaptured} slots went this way.
      </p>
    </li>`;
}

function egMissedRow(c, nShort) {
  if (!c) return "";
  const label = leafLabel(c.path);
  const expected = c.cell.expected != null ? `&ldquo;${safe(c.cell.expected)}&rdquo;` : "blank";
  return `    <li class="ar-eg ar-eg-short">
      <p class="ar-eg-wrote">
        <span class="ar-eg-lbl">The model wrote</span>
        <span class="ar-eg-field">${safe(label)}</span>
        <code class="ar-p-null">blank</code>
      </p>
      <p class="ar-eg-verdict">
        <span class="ar-c ar-short ar-eg-swatch" aria-hidden="true"></span>
        <b>Missed it.</b> Left blank when the answer should have been ${expected}. ${nShort} slots went this way.
      </p>
    </li>`;
}

function egMadeUpRow(c, nFault) {
  if (!c) return "";
  const label = leafLabel(c.path);
  const said = c.cell.sourceSpan
    ? `      <p class="ar-eg-said">
        <span class="ar-eg-lbl">The auditor said</span>
        <q>${safe(c.cell.sourceSpan)}</q>
      </p>
`
    : c.cell.expected != null
      ? `      <p class="ar-eg-said">
        <span class="ar-eg-lbl">The auditor said</span>
        ${safe(c.cell.expected)}
      </p>
`
      : "";
  return `    <li class="ar-eg ar-eg-fault">
${said}      <p class="ar-eg-wrote">
        <span class="ar-eg-lbl">The model wrote</span>
        <span class="ar-eg-field">${safe(label)}</span>
        <code>${safe(c.cell.got)}</code>
      </p>
      <p class="ar-eg-verdict">
        <span class="ar-c ar-fault ar-eg-swatch" aria-hidden="true"></span>
        <b>Wrong or invented.</b> Something on the form that the recording doesn&rsquo;t support
        &mdash; either invented outright, or different from what was actually said. This is the
        outcome that matters most, and it happened ${nFault} times.
      </p>
    </li>`;
}

function finding(run, counts) {
  const t = run.totals;
  const faultN = counts.fault ?? 0;
  const shortN = counts.short ?? 0;

  const cleared = run.hazards ? Object.values(run.hazards.counts).filter((n) => n === 0).length : 0;
  const nHazards = run.hazards ? Object.keys(run.hazards.counts).length : 0;
  const dtDisplay = run.capturedAt.replace("T", " ").slice(0, 16);
  const nCases = caseIdsOf(run).length;
  const nFields = run.leafPaths.length;

  // Built as a filtered array so an absent claim leaves no blank line.
  const claims = [
    faultN > 0
      ? `    <li class="ar-claim ar-claim-fault">
      <p class="ar-claim-n">${faultN}</p>
      <p class="ar-claim-t">slots hold something the recording doesn&rsquo;t say.</p>
      <p class="ar-claim-d">
        Every one is listed in full, with the case wording, under <a href="#problems">Problems</a>.
      </p>
    </li>`
      : null,
    shortN > 0
      ? `    <li class="ar-claim ar-claim-short">
      <p class="ar-claim-n">${shortN}</p>
      <p class="ar-claim-t">slots the auditor stated were left blank on the form.</p>
      <p class="ar-claim-d">
        Every one is listed in full, with the case wording, under <a href="#problems">Problems</a>.
      </p>
    </li>`
      : null,
  ].filter(Boolean);

  return `<section class="ar-finding" aria-labelledby="find-h">
  <h2 class="ar-h" id="find-h">What this run found</h2>
  <ol class="ar-claims">
${claims.join("\n")}
  </ol>
  <p class="ar-caveat">
    No number here is a threshold. Nobody has set an acceptable rate for any of them, and this
    page does not imply one.
  </p>
  <dl class="ar-meta">
    <dt>Run captured</dt>
    <dd><time datetime="${esc(run.capturedAt)}">${esc(dtDisplay)} UTC</time></dd>
    <dt>Backend</dt>
    <dd><code>${safe(run.backend)}</code></dd>
    <dt>Model</dt>
    <dd><code>${safe(run.model)}</code></dd>
    <dt>Settings</dt>
    <dd><code>${safe(settingsSummary(run.settings))}</code></dd>${
      run.settings.planFingerprint == null
        ? ""
        : `
    <dt>Plan fingerprint</dt>
    <dd><code>${safe(run.settings.planFingerprint)}</code></dd>`
    }${
      run.hazards
        ? `
    <dt>Stop-checks</dt>
    <dd>${cleared} of ${nHazards} clear</dd>`
        : ""
    }
    <dt>Corpus</dt>
    <dd><code>${safe(run.corpus.name)}</code> &middot; ${nCases} captures &middot; ${nFields} fields &middot; ${t.judged} slots</dd>
  </dl>
</section>`;
}

function rates(run) {
  const t = run.totals;
  const trend = (field) =>
    [...run.history.map((h) => h.totals[field]), t[field]].filter((v) => v != null);
  const card = (title, value, detail, def, field, label) => `  <div class="ar-card">
    <h3 class="ar-k">${title}</h3>
    <p class="ar-v">${value == null ? "n/a" : `${pct(value)}<span class="ar-u">%</span>`}</p>
    <p class="ar-d">${detail}</p>
    <p class="ar-def">${def}</p>
    ${historyLine(trend(field), label)}
  </div>`;

  return `<section class="ar-rates" aria-label="Rates">
${card(
  "Answered",
  t.answerRate,
  `${t.answered} of ${t.judged} slots the run produced a value for`,
  "Of every judged slot, how often the run produced a value at all.",
  "answerRate",
  "Answered rate",
)}
${card(
  "Accuracy over answered",
  t.accuracyOverAnswered,
  `${t.correct} of ${t.answered} answered slots judged correct`,
  "Of every slot where the run produced a value, how often it was the right one.",
  "accuracyOverAnswered",
  "Accuracy over answered",
)}
${card(
  "Accuracy over all",
  t.accuracyOverAll,
  `${t.correct} of ${t.judged} judged slots judged correct`,
  "Of every judged slot — answered or not — how often the run was right.",
  "accuracyOverAll",
  "Accuracy over all",
)}
</section>`;
}

/**
 * The hazards section renders only from records carrying the self-describing extension
 * (`kind`, `version`, `counts`), and its numbers come from `counts`. A record without the
 * extension renders no hazards section at all.
 */
function gates(run) {
  const hazards = run.hazards;
  if (!hazards) return "";
  const entries = Object.entries(hazards.counts).sort(([a], [b]) => (a < b ? -1 : 1));
  const rows = entries
    .map(([name, n]) => {
      const cls = n === 0 ? "is-clear" : "is-tripped";
      const word = n === 0 ? "clear" : "TRIPPED";
      return `    <li class="ar-gate ${cls}"><span class="ar-gate-n">${esc(name)}</span><span class="ar-gate-c">${n}</span><span class="ar-gate-s">${word}</span></li>`;
    })
    .join("\n");

  return `<section class="ar-gates" aria-label="Stop-checks">
  <h2 class="ar-h">Stop-checks</h2>
  <p class="ar-sub">
    Hazard counts this run carried in its self-describing <code>${esc(hazards.kind)}</code> extension
    (version ${hazards.version}). Each is a count, and any count above zero is worth reading before
    trusting the rates &mdash; they are independent tripwires for named failure mechanisms.
  </p>
  <ul class="ar-gate-list">
${rows}
  </ul>
</section>`;
}

