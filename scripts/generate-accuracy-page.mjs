/**
 * v2 replaces the v1 sparkline with a text line below n=3. At n=1 it is a stated sentence;
 * at n=2 a comparison; at n>=3 the sparkline returns plus the sentence in words.
 */
function historyLine(values, label) {
  const n = values.length;
  if (n === 0) {
    return `<p class="ar-hist ar-hist-none">Run 1 of 1 &mdash; no history to compare against yet</p>`;
  }
  if (n === 1) {
    return `<p class="ar-hist ar-hist-none">Run 1 of 1 &mdash; no history to compare against yet</p>`;
  }
  if (n === 2) {
    const prev = pct(values[0]);
    const now = pct(values[1]);
    return `<p class="ar-hist">Run 2 of 2 &mdash; previous ${prev}%, now ${now}%</p>`;
  }
  // n >= 3: sparkline + text
  const yMax = Math.max(0.02, Math.ceil(125 * Math.max(...values)) / 100);
  const y = (v) => (30 - 26 * (v / yMax)).toFixed(1);
  const x = (i) => (4 + (124 * i) / (n - 1)).toFixed(1);
  const pts = values.map((v, i) => `${x(i)},${y(v)}`).join(" ");
  const dots =
    n <= 8
      ? values
          .map(
            (v, i) =>
              `<circle class="ar-spark-dot${i === n - 1 ? "" : "-past"}" cx="${x(i)}" cy="${y(v)}" r="${i === n - 1 ? 2.5 : 1.5}"/>`,
          )
          .join("")
      : `<circle class="ar-spark-dot" cx="${x(n - 1)}" cy="${y(values[n - 1])}" r="2.5"/>`;
  const lo = pct(Math.min(...values));
  const hi = pct(Math.max(...values));
  const last = pct(values[n - 1]);
  const aria = `${label} over ${n} runs, ${lo}% to ${hi}%, latest ${last}%`;
  return (
    `<svg class="ar-spark" viewBox="0 0 132 34" width="132" height="34" role="img" aria-label="${esc(aria)}">` +
    `<line class="ar-spark-base" x1="4" y1="30.5" x2="128" y2="30.5"/>` +
    `<polyline class="ar-spark-line" points="${pts}"/>${dots}</svg>\n` +
    `<p class="ar-hist">${n} runs &middot; ${lo}%&ndash;${hi}% &middot; latest ${last}%</p>`
  );
}

