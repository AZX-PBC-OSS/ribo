/**
 * A generic, corpus-neutral stale notice. A record is stale when its run fingerprint or its
 * corpus fingerprint differs from the current corpus's — the corpus this page was generated
 * from. Backend, model and settings are never staleness; they render as what was run.
 */
function staleNotice() {
  return `<div class="ar-stale" role="note"><b>This run predates the corpus in the tree.</b>
It was captured against an earlier version of the corpus or its prompt than the corpus this page
was generated from, so its numbers describe a measurement the current corpus would not make.</div>`;
}

