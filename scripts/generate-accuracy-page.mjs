#!/usr/bin/env node
/**
 * Generates `docs/deep-dives/accuracy.md` from the committed acceptance-gate run records.
 *
 * WHY CODEGEN RATHER THAN A VITEPRESS DATA LOADER. A loader hands data to the page, which
 * then has to render it — and rendering inside a VitePress markdown page means `v-html`
 * plus a `<script setup>` block, i.e. Vue. This repo is a React shop with zero `.vue` files
 * and no custom VitePress theme, and the report needs no client-side rendering (`<details>`
 * and a plain IIFE are the only interactivity). So the page is generated whole, exactly the
 * way `docs:api` already generates `docs/reference/` with TypeDoc. No framework, no theme
 * directory, no client-side templating.
 *
 * The output is gitignored and regenerated by `docs:dev` / `docs:build`, so it can never
 * drift from the artifacts.
 *
 * READS THE ARTIFACTS DIRECTLY. `acceptance/run-record.ts`'s zod schemas remain the
 * authority on the format; this is a downstream reader that cannot import them (it is
 * plain `.mjs`, and the store's TypeScript imports do not resolve under bare Node). It
 * therefore fails loudly on anything unexpected rather than rendering a partial page —
 * see `requireShape` below.
 *
 * Design: docs/roadmap/design/accuracy-report-visual-design.md (v2)
 */
