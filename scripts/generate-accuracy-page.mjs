#!/usr/bin/env node
/**
 * Generates `docs/deep-dives/accuracy.md` from eval run records (the `@azx/ribo-cli`
 * record format) and a corpus directory.
 *
 * WHY CODEGEN RATHER THAN A VITEPRESS DATA LOADER. A loader hands data to the page, which
 * then has to render it — and rendering inside a VitePress markdown page means `v-html`
 * plus a `<script setup>` block, i.e. Vue. This repo is a React shop with zero `.vue` files
 * and no custom VitePress theme, and the report needs no client-side rendering (`<details>`
 * and a plain IIFE are the only interactivity). So the page is generated whole, exactly the
 * way `docs:api` already generates `docs/reference/` with TypeDoc. No framework, no theme
 * directory, no client-side templating.
 *
 * The output is gitignored and regenerated by `docs:dev` / `docs:build`, so it can never
 * drift from the artifacts.
 *
 * TWO REQUIRED ARGUMENTS. `node scripts/generate-accuracy-page.mjs <records-dir> <corpus-dir>`
 * — the run records to render and the corpus the page's staleness is judged against. There
 * are no flags and no defaults: an omitted argument is a loud usage error naming it, never a
 * silent directory the page keeps reading. The root `docs:accuracy` script passes both
 * explicitly. A records directory that does not exist reads as zero records — that is the
 * page's one empty state, what renders on a clean checkout before the first `ribo eval --out`
 * baseline lands; the guard fires before any corpus is read, which is what keeps `docs:build`
 * green on a clean checkout.
 *
 * READS THE CLI, NOT ITS OWN COPY. The records are read through `readEvalRunRecords`
 * (`@azx/ribo-cli`), so they are zod-parsed against the run-record schema on read — an
 * old-format or malformed record fails loudly naming the file, and this generator carries no
 * record parsing of its own. Staleness is judged with the CLI's own exported
 * `runFingerprint` / `corpusFingerprint` against the corpus named by the second argument —
 * never a second copy of the fingerprint logic and never a fixture-file hash. Every verdict
 * lookup goes through `bucketOf`, which throws on a verdict outside the eval vocabulary.
 *
 * Design: docs/roadmap/design/ribo-cli-eval-design.md §10
 */
