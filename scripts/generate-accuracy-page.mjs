const PREAMBLE = `---
title: Extraction accuracy
head:
  - - script
    - src: /accuracy-report.js
      defer: true
---

<!--
  GENERATED by scripts/generate-accuracy-page.mjs from eval run records. Do not edit by
  hand — \`pnpm docs:dev\` and \`pnpm docs:build\` regenerate it.
-->

`;

const EMPTY_STATE_PAGE = `${PREAMBLE}**No accuracy runs have been published yet.** The first one is produced with
\`ribo eval\` — the eval harness writes one record per arm into the directory named by
\`--out\`. An operator publishes a baseline for this page by running, for example,
\`ribo eval --out packages/ribo-adapter-snuggpro/acceptance/runs/\`; the page regenerates on the
next \`pnpm docs:build\`.
`;

/**
 * A blank or whitespace-only line inside an HTML block ends that block as far as
 * markdown-it is concerned. Everything after it is re-parsed as markdown, indented lines
 * become code blocks, and the enclosing tags never match — Vue's SFC compiler then fails
 * the build with a bare "Element is missing end tag" pointing at a tag that is, in fact,
 * perfectly balanced. That error names a symptom several hundred lines from the cause,
 * which is why this checks the real invariant at the point it is violated.
 */
function assertNoBlankLines(html, label) {
  const lines = html.split("\n");
  for (const [i, line] of lines.entries()) {
    if (line.trim() === "") {
      throw new Error(
        `generate-accuracy-page: emitted a blank line at line ${i + 1} of the "${label}" ` +
          `block. Nothing inside <div class="ar"> may be blank or whitespace-only — it ` +
          `silently terminates the HTML block and breaks the VitePress build. Build the ` +
          `offending section as a filtered array of lines rather than a template with an ` +
          `empty conditional branch.`,
      );
    }
  }
}

function renderRecord(run, total, keys) {
  requireDenseGrid(run, `${run.backend} · ${run.model}`);
  const { found, index } = collectProblems(run);
  const counts = bucketCounts(run);
  const stale =
    run.fingerprint !== keys.currentRunKey || run.corpus.fingerprint !== keys.currentCorpusKey;
  const label = `${run.backend} · ${run.model}`;
  // Joined with a SINGLE newline, never a blank line. A blank line inside an HTML block
  // ends that block as far as markdown-it is concerned, so the outer `<div class="ar">`
  // would never be matched by its `</div>` and Vue's SFC compiler fails the build with
  // "Element is missing end tag". Blank lines are only safe BETWEEN records, where each
  // div is already closed.
  const body = [
    `<div class="ar">`,
    stale ? staleNotice() : "",
    intro(run),
    workedExample(run),
    finding(run, counts),
    rates(run),
    gates(run),
    legend(run, counts),
    grid(run, index),
    problems(found),
    method(run),
    `</div>`,
  ]
    .filter((s) => s !== "")
    .join("\n");
  assertNoBlankLines(body, label);
  return total > 1 ? `## ${esc(label)}\n\n${body}` : body;
}

/**
 * Render the page and write it to `out`.
 * @param argv - The positional arguments: the records directory, then the corpus directory.
 * @param opts - `out` names the page to write (tests point it at a temp file); `log` is the
 *   progress sink.
 */
export function main(argv = process.argv.slice(2), { out = OUT, log = console.log } = {}) {
  if (argv.length === 0) {
    throw new Error(
      "generate-accuracy-page: missing the records directory argument — pass " +
        "<records-dir> <corpus-dir>",
    );
  }
  if (argv.length === 1) {
    throw new Error(
      "generate-accuracy-page: missing the corpus directory argument — pass " +
        "<records-dir> <corpus-dir>",
    );
  }
  if (argv.length > 2) {
    throw new Error(
      "generate-accuracy-page: exactly two arguments are required, <records-dir> <corpus-dir> — " +
        `got ${argv.length}`,
    );
  }
  const recordsDir = resolve(argv[0]);
  const corpusDir = resolve(argv[1]);

  // A missing directory reads as zero records — the empty state is normal, not a fault.
  // This guard fires BEFORE any corpus read: on a clean checkout there is no corpus in the
  // tree the page can trust either, and the empty state is the honest page for it.
  const records = readEvalRunRecords(recordsDir);
  if (records.length === 0) {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, EMPTY_STATE_PAGE);
    log(`[accuracy] no records found in ${recordsDir} — wrote the empty-state page`);
    return;
  }

  let corpus;
  try {
    corpus = loadCorpus(corpusDir);
  } catch (cause) {
    throw new Error(
      `generate-accuracy-page: the corpus directory "${corpusDir}" could not be loaded: ` +
        `${cause instanceof Error ? cause.message : String(cause)}`,
      { cause },
    );
  }
  const keys = {
    currentRunKey: runFingerprint(corpus.schemaDocument, corpus.manifest.prompt),
    currentCorpusKey: corpusFingerprint(corpus),
  };

  const sections = records.map((run) => renderRecord(run, records.length, keys));
  writeFileSync(out, `${PREAMBLE}${sections.join("\n\n")}\n\n<style>\n${STYLE}</style>\n`);
  log(`[accuracy] wrote ${out} from ${records.length} record(s) against ${corpusDir}`);
}

/** The CLI entry: a usage or render failure is a non-zero exit naming the cause on stderr. */
function cli() {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  cli();
}
