function grid(run, problemIndex) {
  const slugs = run.transcripts.map((t) => t.slug);
  const short = (s) => s.replace(/^(\d+)-.*/, "$1");

  // Find the hot column (most flags).
  const colFlags = new Map(slugs.map((s) => [s, 0]));
  for (const path of run.leafPaths) {
    for (const slug of slugs) {
      const cell = run.grid[path]?.[slug];
      const bucket = cell ? BUCKET[cell.verdict] : "absent";
      if (bucket !== "captured" && bucket !== "absent") {
        colFlags.set(slug, colFlags.get(slug) + 1);
      }
    }
  }
  const maxFlags = Math.max(...colFlags.values());
  const hotSlug =
    maxFlags >= 4 ? [...colFlags.entries()].find(([_, n]) => n === maxFlags)?.[0] : null;

  const totalSlots = run.leafPaths.length * slugs.length;
  const totalFlags = [...colFlags.values()].reduce((a, b) => a + b, 0);

  const head = `      <tr>
        <th class="ar-corner" scope="col">Form field</th>
${slugs
  .map(
    (s) =>
      `        <th class="ar-ch${s === hotSlug ? " ar-ch-hot" : ""}" scope="col" title="${esc(s)}"><span>${esc(short(s))}</span></th>`,
  )
  .join("\n")}
        <th class="ar-mh" scope="col">found</th>
        <th class="ar-mh" scope="col">flags</th>
      </tr>`;

  // One <tbody> per schema subtree, in schema order.
  const groups = [];
  for (const path of run.leafPaths) {
    const g = path.split(".")[0];
    if (groups.length === 0 || groups[groups.length - 1].name !== g) {
      groups.push({ name: g, paths: [] });
    }
    groups[groups.length - 1].paths.push(path);
  }

  const bodies = groups
    .map((group) => {
      const rows = group.paths
        .map((path) => {
          let cap = 0;
          let flag = 0;
          const cells = slugs
            .map((slug) => {
              const cell = run.grid[path]?.[slug];
              const verdict = cell?.verdict ?? "correct-null";
              const bucket = BUCKET[verdict] ?? "excused";
              if (bucket === "captured") cap++;
              if (bucket !== "captured" && bucket !== "absent") flag++;
              if (bucket === "absent") return `        <td class="ar-c ar-absent"></td>`;
              if (bucket === "captured")
                return `        <td class="ar-c ar-captured"><span class="ar-sr">found it</span></td>`;
              const sr = `<span class="ar-sr">${BUCKET_SR[bucket]} &mdash; ${esc(verdict)}</span>`;
              const id = problemIndex.get(`${path} ${slug}`);
              const inner = id ? `<a href="#${id}" data-ar-p="${id}">${sr}</a>` : sr;
              return `        <td class="ar-c ar-${bucket}">${inner}</td>`;
            })
            .join("\n");
          const capCell =
            cap === 0
              ? `        <td class="ar-m ar-m-none">&mdash;</td>`
              : `        <td class="ar-m">${cap}</td>`;
          const flagCell =
            flag === 0
              ? `        <td class="ar-m">&middot;</td>`
              : `        <td class="ar-m ar-m-hot">${flag}</td>`;
          const rowFlag = flag > 0 ? " ar-row-flag" : "";
          const label = leafLabel(path);
          return `      <tr class="ar-row${rowFlag}">
        <th class="ar-rh" scope="row">
          <span class="ar-rh-en">${safe(label)}</span>
          <code class="ar-rh-id">${esc(path)}</code>
        </th>
${cells}
${capCell}
${flagCell}
      </tr>`;
        })
        .join("\n");
      const gLabel = GROUP_LABEL[group.name] ?? group.name;
      return `    <tbody class="ar-group">
      <tr><th class="ar-gh" colspan="${slugs.length + 3}" scope="colgroup">${esc(gLabel)}</th></tr>
${rows}
    </tbody>`;
    })
    .join("\n");

  const foot = `    <tfoot>
      <tr>
        <th class="ar-rh ar-foot" scope="row">flags per transcript</th>
${slugs
  .map((s) => {
    const n = colFlags.get(s);
    return n === 0
      ? `        <td class="ar-m">&middot;</td>`
      : `        <td class="ar-m${n >= 4 ? " ar-m-hot" : ""}">${n}</td>`;
  })
  .join("\n")}
        <td class="ar-m"></td>
        <td class="ar-m">${totalFlags}</td>
      </tr>
    </tfoot>`;

  return `<section aria-labelledby="coverage-h">
  <h2 class="ar-h" id="coverage-h">Every slot</h2>
  <p class="ar-sub">
    Rows are in form order and never re-sorted, so any two runs of this page can be compared square
    for square.
  </p>
  <fieldset class="ar-filter">
    <legend class="ar-sr">Which slots to show</legend>
    <input class="ar-sr ar-filter-in" type="radio" name="ar-view" id="ar-view-all" checked />
    <label class="ar-filter-opt" for="ar-view-all">All ${totalSlots}</label>
    <input class="ar-sr ar-filter-in" type="radio" name="ar-view" id="ar-view-flag" />
    <label class="ar-filter-opt" for="ar-view-flag">Only the ${totalFlags} worth reading</label>
  </fieldset>
  <div class="ar-scroll" tabindex="0" role="group" aria-label="Slot grid, scrollable sideways">
    <table class="ar-grid" id="ar-grid">
      <caption class="ar-sr">
        Outcome for each of ${run.leafPaths.length} form fields on each of ${slugs.length} transcripts. Empty squares are
        &ldquo;nothing to find&rdquo;. Per-row totals are in the two right-hand columns; the
        Problems section lists every non-empty outcome in full.
      </caption>
      <thead>
${head}
      </thead>
${bodies}
${foot}
    </table>
  </div>
  <div class="ar-inspect" id="ar-inspect" hidden>
    <div class="ar-inspect-head">
      <p class="ar-inspect-t" id="ar-inspect-t"></p>
      <button class="ar-inspect-x" type="button" data-ar-close>Close</button>
    </div>
    <div class="ar-inspect-body" id="ar-inspect-body" aria-live="polite"></div>
  </div>
  <p class="ar-sub ar-inspect-hint">
    Marked squares open their full detail below the grid. Without JavaScript they jump to the same
    detail in <a href="#problems">Problems</a>.
  </p>
</section>`;
}

/** Collect every non-absent, non-captured cell, ordered fault -> short -> excused. */
function collectProblems(run) {
  const found = [];
  for (const path of run.leafPaths) {
    for (const t of run.transcripts) {
      const cell = run.grid[path]?.[t.slug];
      if (!cell) continue;
      const bucket = BUCKET[cell.verdict];
      if (bucket === "absent" || bucket === "captured") continue;
      found.push({ path, slug: t.slug, cell, bucket });
    }
  }
  const rank = { fault: 0, short: 1, excused: 2 };
  found.sort((a, b) => rank[a.bucket] - rank[b.bucket]);
  const index = new Map();
  found.forEach((p, i) => {
    p.id = `p-${String(i + 1).padStart(2, "0")}`;
    index.set(`${p.path} ${p.slug}`, p.id);
  });
  return { found, index };
}

function problems(found) {
  if (found.length === 0) {
    return `<section id="problems" aria-labelledby="problems-h">
  <h2 class="ar-h" id="problems-h">Problems &mdash; none</h2>
  <p class="ar-sub">Every cell is either <b>found it</b> or <b>nothing to find</b>.</p>
</section>`;
  }

  const dd = (v) =>
    v === null || v === undefined
      ? `<dd class="ar-p-null">blank</dd>`
      : `<dd><code>${safe(v)}</code></dd>`;

  let heading = "";
  const entries = found
    .map((p) => {
      let h = "";
      if (p.bucket !== heading) {
        heading = p.bucket;
        const n = found.filter((q) => q.bucket === p.bucket).length;
        h = `  <h3 class="ar-bh ar-bh-${p.bucket}">${BUCKET_LABEL[p.bucket]} &mdash; ${n}</h3>\n`;
      }
      const c = p.cell;
      const label = leafLabel(p.path);
      const whatHappenedDt = p.bucket === "excused" ? "Why not counted" : "What happened";

      // Built as a filtered array, never as a template with an empty conditional branch.
      // An optional field that renders to "" leaves a WHITESPACE-ONLY line, which
      // markdown-it counts as blank — that ends the surrounding HTML block, and every
      // following indented line becomes an indented code block, so `</details>` never
      // matches its opening tag and Vue's SFC compiler fails the build. Nothing emitted
      // inside `.ar` may ever produce a blank or whitespace-only line.
      const rows = [
        `      <dt>Correct answer</dt>${dd(c.expected)}`,
        `      <dt>Model wrote</dt>${dd(c.got)}`,
        `      <dt>Quote given</dt>${c.sourceSpan ? `<dd><q>${safe(c.sourceSpan)}</q></dd>` : `<dd class="ar-p-null">none</dd>`}`,
        `      <dt>Quote problem</dt>${c.spanIssue ? `<dd>${safe(c.spanIssue)}</dd>` : `<dd class="ar-p-null">none</dd>`}`,
        c.detail ? `      <dt>${whatHappenedDt}</dt><dd>${safe(c.detail)}</dd>` : null,
        `      <dt>Field</dt><dd><code>${esc(p.path)}</code></dd>`,
      ].filter(Boolean);

      return `${h}  <details class="ar-p ar-p-${p.bucket}" id="${p.id}">
    <summary>
      <span class="ar-p-v">${esc(c.verdict)}</span>
      <span class="ar-p-leaf">${safe(label)}</span>
      <span class="ar-p-t">${esc(p.slug)}</span>
    </summary>
    <dl class="ar-p-body">
${rows.join("\n")}
    </dl>
  </details>`;
    })
    .join("\n");

  return `<section id="problems" aria-labelledby="problems-h">
  <h2 class="ar-h" id="problems-h">Problems &mdash; all ${found.length}</h2>
  <p class="ar-sub">
    Every slot that was not either &ldquo;found it&rdquo; or &ldquo;nothing to find&rdquo;, in full,
    with the transcript wording. Nothing is summarised away.
  </p>
${entries}
</section>`;
}

function method(run) {
  const t = run.totals;
  const hallN = t.hallucinationHard ?? 0;
  const hallD = t.gtNull ?? 0;
  const wrongN = (t.wrong ?? 0) + (t.healthWrong ?? 0);
  const missN = t.miss ?? 0;
  const missD = (t.gtNonNull ?? 0) - (t.missExcused ?? 0);
  const enumN = t.enumCorrect ?? 0;
  const enumD = t.enumGtMember ?? 0;
  const hMissN = t.hMiss ?? 0;

  return `<section class="ar-method" aria-labelledby="method-h">
  <h2 class="ar-h" id="method-h">How these numbers were worked out</h2>
  <dl class="ar-method-list">
    <dt>Made-up rate</dt>
    <dd>${hallN} &divide; ${hallD}. The ${hallD} is every slot whose correct answer was blank. The ${hallN} are the
      inventions among them. The ${wrongN} contradictions are not in this rate &mdash; they had a
      stated answer, so they belong to a different denominator; all ${hallN + wrongN} are in Problems.</dd>
    <dt>Miss rate</dt>
    <dd>${missN} &divide; ${missD}. The ${missD} is every non-health slot with something to find, after
      removing the ${t.missExcused ?? 0} not-counted slots. The ${hMissN} health misses are reported on their own and
      never folded in, by design.</dd>
    <dt>Fixed-choice accuracy</dt>
    <dd>${enumN} &divide; ${enumD}: fixed-choice slots with a stated answer, where the model picked the
      right member of the list.</dd>
    <dt>Why the stop-checks can pass while a rate is non-zero</dt>
    <dd>The checks test named failure mechanisms; the rates count outcomes. Both are real cases in this run,
      and both are arguments for widening a check.</dd>
    <dt>What this does not tell you</dt>
    <dd>${run.transcripts.length} transcripts, all from one region and one auditor&rsquo;s vocabulary. These are
      measurements of this corpus. They are a floor observed under these conditions &mdash;
      not a bound, not a forecast, and not a threshold anyone has agreed to.</dd>
  </dl>
</section>`;
}

