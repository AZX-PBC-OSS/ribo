/**
 * The one verdict→bucket lookup. `correct` splits on the expectation: a correct answer to a
 * declared absence renders as the correctly-absent state, a correct captured value as
 * "found it". Any verdict outside the eval vocabulary throws — an unknown verdict is a loud
 * error at every lookup path, never an "excused" cell and never a silent `undefined`.
 * @param cell - The scored cell.
 * @returns The page's visual bucket.
 */
function bucketOf(cell) {
  const verdict = cell?.verdict;
  if (verdict === "correct") return cell.expected == null ? "absent" : "captured";
  const bucket = VERDICT_BUCKET[verdict];
  if (bucket === undefined) {
    throw new Error(
      `generate-accuracy-page: unknown verdict ${JSON.stringify(verdict)} — the page buckets ` +
        `only the eval vocabulary (${EVAL_VERDICTS.join(", ")}). The record predates or postdates ` +
        `this generator's vocabulary; re-score the run, or fix the generator.`,
    );
  }
  return bucket;
}

/** The non-`correct` verdicts' buckets. `correct` splits on `expected` inside `bucketOf`. */
const VERDICT_BUCKET = {
  missed: "short",
  wrong: "fault",
  hallucinated: "fault",
  unscorable: "excused",
};

const BUCKET_ORDER = ["absent", "captured", "excused", "short", "fault"];
const BUCKET_LABEL = {
  absent: "Nothing to find",
  captured: "Found it",
  excused: "Not counted",
  short: "Missed it",
  // NOT "Hallucinations". This bucket is hallucinations PLUS `wrong` — cases where the
  // auditor did state a value and the model wrote a different one, which is not a
  // hallucination. Naming the bucket "Hallucinations" would put two different numbers
  // behind one word.
  fault: "Wrong or invented",
};

/** Which verdicts a bucket row of the legend names. A description index, not a lookup. */
const BUCKET_VERDICTS = BUCKET_ORDER.reduce((acc, b) => {
  acc[b] = [];
  return acc;
}, {});
for (const v of EVAL_VERDICTS) {
  if (v === "correct") {
    BUCKET_VERDICTS.absent.push(v);
    BUCKET_VERDICTS.captured.push(v);
  } else {
    BUCKET_VERDICTS[VERDICT_BUCKET[v]].push(v);
  }
}

