#!/usr/bin/env node
/**
 * @file Vendor field descriptions for the Snugg Pro extraction schema.
 *
 *   pnpm snugg:refresh   regenerate `descriptions.generated.ts` from the live spec
 *   pnpm snugg:check     fail if what we have no longer matches the live spec
 *
 * ## Why the vendor's own words, and not ours
 *
 * The extraction schema tells an LLM what 51 fields mean. Those sentences were
 * originally paraphrased from our JSDoc, while the vendor publishes an authoritative
 * description for 51 of them in `swagger.json` — the same text a Snugg Pro user reads
 * in their UI. Anchoring on the vendor's wording anchors our vocabulary to theirs.
 *
 * Our own notes are still worth having, but they say a different thing: what mistake NOT
 * to make ("never ACH50, never CFM25"). `schema.ts` composes vendor-sentence-then-ours,
 * so the model gets the definition and the prohibition.
 *
 * ## Why the spec is NOT committed
 *
 * It is 1.2 MB of vendor JSON that would go stale the moment they deploy. The DERIVED
 * text is committed instead — small, reviewable, diffable — and the check tells us when
 * it stops matching.
 *
 * ## Why regeneration is not automatic
 *
 * Same reasoning as `refresh-target.mjs`: regenerating is an intentional act, so a vendor
 * wording change lands in a reviewable diff rather than silently altering the prompt an
 * extraction model sees. `--check` runs in CI and REPORTS drift; only a human runs
 * `--refresh`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SPEC_URL = "https://app.snuggpro.com/apidocs/swagger.json";
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(repoRoot, "packages/ribo-adapter-snuggpro/src/descriptions.generated.ts");
const schemaFile = path.join(repoRoot, "packages/ribo-adapter-snuggpro/src/schema.ts");

/** Every `properties.<name>.description` in the spec, first occurrence wins. */
function collectDescriptions(node, into = new Map()) {
  if (Array.isArray(node)) {
    for (const child of node) collectDescriptions(child, into);
    return into;
  }
  if (node === null || typeof node !== "object") return into;
  const properties = node.properties;
  if (properties && typeof properties === "object") {
    for (const [name, body] of Object.entries(properties)) {
      if (body && typeof body === "object" && typeof body.description === "string") {
        if (!into.has(name)) into.set(name, body.description.trim().replace(/\s+/g, " "));
      }
    }
  }
  for (const child of Object.values(node)) collectDescriptions(child, into);
  return into;
}

/**
 * Every `name:` key our schema declares, at any indentation.
 *
 * Deliberately over-inclusive: it is intersected with the vendor's own property names
 * below, so a key the vendor does not describe simply drops out. Matching a FIXED indent
 * was the first version and it was wrong — wrapping the groups in a helper shifted every
 * leaf two spaces deeper and the check reported nine fields as vendor drift when nothing
 * on the vendor's side had moved. A brittle source regex that fails CLOSED, by silently
 * finding fewer leaves, is worse than one that finds too many.
 */
function ourLeafNames() {
  const source = readFileSync(schemaFile, "utf8");
  return [...new Set([...source.matchAll(/^\s+(\w+):\s/gm)].map((m) => m[1]))].sort();
}

function render(pairs) {
  const entries = pairs.map(([name, text]) => `  ${name}: ${JSON.stringify(text)},`).join("\n");
  return `// GENERATED by \`pnpm snugg:refresh\` — do not edit by hand.
//
// Source:    ${SPEC_URL}
// Refreshed: ${new Date().toISOString().slice(0, 10)}
// Leaves:    ${pairs.length}
//
// The vendor's own description for each field we extract — the same sentence a Snugg Pro
// user reads in their UI. \`schema.ts\` composes this with our own note, where we have one,
// so the model gets both the definition and the prohibition that matters for extraction.
//
// \`pnpm snugg:check\` fails when this no longer matches the live spec. Regeneration is
// deliberate rather than automatic, so a vendor rewording lands in a reviewable diff
// instead of silently changing what an extraction model is told.

/** Vendor descriptions, keyed by the leaf name as it appears in \`snuggValuesSchema\`. */
export const VENDOR_DESCRIPTIONS: Readonly<Record<string, string>> = {
${entries}
};
`;
}

const mode = process.argv.includes("--refresh") ? "refresh" : "check";

let spec;
try {
  const response = await fetch(SPEC_URL, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  spec = await response.json();
} catch (cause) {
  // A network failure is NOT drift, and must not be reported as one. Exit 0 with a loud
  // warning: a build that fails because a vendor's docs host is down teaches people to
  // ignore this check, which is worse than occasionally not running it.
  console.warn(`\n  snugg:${mode} SKIPPED — could not reach the spec (${String(cause)}).`);
  console.warn("  This is not a drift failure. Re-run when the vendor's docs are reachable.\n");
  process.exit(0);
}

const vendor = collectDescriptions(spec);
const pairs = ourLeafNames()
  .filter((name) => vendor.has(name))
  .map((name) => [name, vendor.get(name)]);

if (mode === "refresh") {
  writeFileSync(outFile, render(pairs), "utf8");
  console.log(`snugg:refresh — wrote ${pairs.length} vendor descriptions to`);
  console.log(`  ${path.relative(repoRoot, outFile)}`);
  const missing = ourLeafNames().filter((name) => !vendor.has(name));
  if (missing.length > 0) {
    console.log(`\n  ${missing.length} leaves have no vendor description: ${missing.join(", ")}`);
    console.log("  Those keep whatever note schema.ts gives them, which is the intended fallback.");
  }
  process.exit(0);
}

// --check: compare the DATA, not the rendered text.
//
// Comparing rendered output was the first version and it was wrong twice over: Prettier
// rewraps the generated file after it is written, so a byte comparison reported formatting
// as vendor drift, and the line-regex used to parse it back silently dropped any entry
// Prettier had wrapped. Importing the module compares what the code actually uses.
let committed;
try {
  ({ VENDOR_DESCRIPTIONS: committed } = await import(outFile));
} catch (cause) {
  console.error(`\n  snugg:check FAILED — cannot read ${path.relative(repoRoot, outFile)}.`);
  console.error(`  ${String(cause)}`);
  console.error("  Run `pnpm snugg:refresh`.\n");
  process.exit(1);
}

const live = Object.fromEntries(pairs);
const changed = Object.keys(live).filter((k) => committed[k] !== live[k]);
const removed = Object.keys(committed).filter((k) => !(k in live));
const added = Object.keys(live).filter((k) => !(k in committed));

if (changed.length === 0 && removed.length === 0 && added.length === 0) {
  console.log(`snugg:check — ${pairs.length} vendor descriptions match the live spec.`);
  process.exit(0);
}

console.error("\n  snugg:check FAILED — the vendor spec no longer matches what we committed.\n");
for (const name of added) console.error(`    + ${name} — vendor now describes this field`);
for (const name of removed) console.error(`    - ${name} — vendor no longer describes this field`);
for (const name of changed) {
  console.error(`    ~ ${name}`);
  console.error(`        ours:   ${String(committed[name]).slice(0, 100)}`);
  console.error(`        vendor: ${live[name].slice(0, 100)}`);
}
console.error("\n  This is a real change on the vendor's side, not a flake. Read the diff, then");
console.error("  run `pnpm snugg:refresh` and review what it does to the extraction prompt.\n");
process.exit(1);
