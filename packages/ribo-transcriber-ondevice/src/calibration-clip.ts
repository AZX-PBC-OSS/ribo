/**
 * @file The calibration clip: ~5 s of real speech, used once at `prime()` time to
 * measure this device's real-time factor.
 *
 * **Why speech and not silence or a tone.** Whisper's decoder cost scales with the
 * number of tokens it emits. A silent or synthetic clip decodes almost instantly,
 * which would understate the real-time factor and let a slow device sail through the
 * gate — the exact failure the gate exists to prevent.
 *
 * **Why Opus in WebM.** It is what `Recorder` actually produces, so `decodeTo16kMono`
 * handles it on the same path a real recording takes, and the measured factor includes
 * decode rather than inference alone. It is also about eight times smaller than the
 * equivalent WAV, which matters for a committed asset.
 *
 * **Why base64 in a module rather than a committed `.webm`.** A `?url` asset import is
 * Vite-specific, and this is a published library consumed by unknown bundlers. Inlining
 * costs ~26 KB of source and works everywhere with no build configuration. (A `.wav`
 * under `testdata/` was not an option either — `.gitignore` excludes those.)
 *
 * Regenerating: record ~5 s of speech through Chromium's `MediaRecorder` with
 * `audioBitsPerSecond: 32000`, then base64 the bytes. Real speech through the real
 * recorder is the point; an ffmpeg-muxed file exercises a different muxer.
 */

