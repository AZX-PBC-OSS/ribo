import { fallbackTranscriber, unsupportedFallsThrough } from "@azx/ribo-core";
import { expect, test, beforeEach } from "vitest";

import { PdfjsTranscriber } from "./index.js";
import { PDFJS_ENGINE } from "./config.js";
import { resetPdfjsCache } from "./pdf-text.js";
import type { PdfjsModule } from "./config.js";

// The worker URL is supplied by the test, not the library (AGENTS.md §5.2).
// A `?url` import of pdfjs-dist's worker build is the intended shape: a test
// is not library code, so §5.2's injection rule does not bind it.
import workerUrl from "pdfjs-dist/build/pdf.worker.min.mjs?url";

// Fixture PDFs — hand-written as raw PDF bytes, no generator dependency.
//
// text-layer.pdf (754 bytes): a two-page PDF with a real text layer.
//   Page 1: "The first page says hello world to the reader here"
//   Page 2: "The second page contains different text content"
//   Structure: Catalog → Pages(Kids[Page1, Page2]) → Page(Resources/Font,
//   Contents=stream) → Font(Helvetica). Uses startxref 0 to force pdf.js's
//   recovery scan, avoiding fragile xref offset arithmetic.
//
// no-text-layer.pdf (301 bytes): a one-page PDF with no /Contents entry.
//   getTextContent() returns an empty items array — the no-text-layer guard
//   fires because zero non-whitespace characters survive the strip.
//
// Both were generated by a one-off Node script (writeFileSync with hand-built
// PDF object strings and a computed xref table). Regenerate from the structure
// above — no PDF library needed, just string concatenation and byte-offset
// arithmetic.
import textLayerPdfUrl from "./fixtures/text-layer.pdf?url";
import noTextLayerPdfUrl from "./fixtures/no-text-layer.pdf?url";

import type { DocumentCapture } from "@azx/ribo-core";

/**
 * Browser tests for pdf.js text extraction — the Task 6 must-fail tests from
 * `docs/roadmap/design/document-transcription-plan.md`.
 *
 * These MUST be `*.browser.test.ts`: pdf.js needs a real `Worker` and real
 * structured-clone behaviour. A node test would mock the very thing under test.
 * The root vitest config's `browser` project globs all
 * `packages/ ... /src/ ... /**.browser.test.{ts,tsx}` files, so this file is
 * picked up with no config edit.
 */

beforeEach(() => {
  // Reset the memoized pdf.js promise so each test starts clean.
  resetPdfjsCache();
});

async function fetchPdf(url: string): Promise<Blob> {
  const response = await fetch(url);
  return response.blob();
}

function makeDocumentCapture(pageCount: number): DocumentCapture {
  return {
    id: `doc-${pageCount}`,
    kind: "document",
    capturedAt: "2026-09-09T12:00:00.000Z",
    mimeType: "application/pdf",
    ctx: {},
    pageCount,
  };
}

test("a two-page text-layer PDF yields both pages' known strings with page markers in order", async () => {
  const bytes = await fetchPdf(textLayerPdfUrl);
  const t = new PdfjsTranscriber({ workerSrc: workerUrl });
  const item = makeDocumentCapture(2);
  const transcript = await t.transcribe(item, bytes);

  // Both pages' known strings are present.
  expect(transcript.text).toContain("hello world");
  expect(transcript.text).toContain("different text");

  // Page markers are present in the exact form, in order, each on its own line.
  expect(transcript.text).toContain("\n===== PAGE 1 =====\n");
  expect(transcript.text).toContain("\n===== PAGE 2 =====\n");
  const page1Pos = transcript.text.indexOf("===== PAGE 1 =====");
  const page2Pos = transcript.text.indexOf("===== PAGE 2 =====");
  expect(page1Pos).toBeGreaterThan(-1);
  expect(page2Pos).toBeGreaterThan(page1Pos);
});

test("markers are numbered from 1, not 0", async () => {
  const bytes = await fetchPdf(textLayerPdfUrl);
  const t = new PdfjsTranscriber({ workerSrc: workerUrl });
  const item = makeDocumentCapture(2);
  const transcript = await t.transcribe(item, bytes);

  expect(transcript.text).toContain("===== PAGE 1 =====");
  expect(transcript.text).not.toContain("===== PAGE 0 =====");
});

test("a no-text-layer PDF throws UnsupportedItemError with reason no-text-layer", async () => {
  const bytes = await fetchPdf(noTextLayerPdfUrl);
  const t = new PdfjsTranscriber({ workerSrc: workerUrl });
  const item = makeDocumentCapture(1);

  await expect(t.transcribe(item, bytes)).rejects.toMatchObject({
    name: "UnsupportedItemError",
    reason: "no-text-layer",
    engine: PDFJS_ENGINE,
  });
});

test("a no-text-layer failure leaves capability() reporting ready", async () => {
  const bytes = await fetchPdf(noTextLayerPdfUrl);
  const t = new PdfjsTranscriber({ workerSrc: workerUrl });
  const item = makeDocumentCapture(1);

  // Capability is ready before the attempt.
  const capBefore = await t.capability();
  expect(capBefore.status).toBe("ready");

  // The transcribe fails with no-text-layer.
  await expect(t.transcribe(item, bytes)).rejects.toMatchObject({
    reason: "no-text-layer",
  });

  // Capability is still ready — one unreadable PDF must never demote pdf.js.
  const capAfter = await t.capability();
  expect(capAfter.status).toBe("ready");
});

test("pdf.js is not imported until the first transcribe() call, and is imported once across two calls", async () => {
  const bytes = await fetchPdf(textLayerPdfUrl);
  const item = makeDocumentCapture(2);

  let loadCount = 0;
  const countingLoader = async (): Promise<PdfjsModule> => {
    loadCount++;
    return (await import("pdfjs-dist")) as unknown as PdfjsModule;
  };
  const t = new PdfjsTranscriber({ workerSrc: workerUrl, loadPdfjs: countingLoader });

  // Not loaded at construction or capability time.
  expect(loadCount).toBe(0);
  await t.capability();
  expect(loadCount).toBe(0);

  // Loaded on first transcribe.
  await t.transcribe(item, bytes);
  expect(loadCount).toBe(1);

  // Not loaded again on second transcribe — memoized.
  await t.transcribe(item, bytes);
  expect(loadCount).toBe(1);
});

test("the whole document reaches the output: marker count equals page count", async () => {
  const bytes = await fetchPdf(textLayerPdfUrl);
  const t = new PdfjsTranscriber({ workerSrc: workerUrl });
  const item = makeDocumentCapture(2);
  const transcript = await t.transcribe(item, bytes);

  // Count the page markers — must equal the page count, no page router.
  const markerCount = (transcript.text.match(/===== PAGE \d+ =====/g) ?? []).length;
  expect(markerCount).toBe(2);
});

test("a transcript produced through the fallback ladder carries engine pdfjs", async () => {
  const bytes = await fetchPdf(textLayerPdfUrl);
  const item = makeDocumentCapture(2);

  const pdfjs = new PdfjsTranscriber({ workerSrc: workerUrl });
  const ladder = fallbackTranscriber([pdfjs], unsupportedFallsThrough);
  const transcript = await ladder.transcribe(item, bytes);

  // The transcript carries the engine id of the implementation that ran,
  // not the wrapper's. The wrapper defaults to "fallback".
  expect(transcript.engine).toBe("pdfjs");
  expect(transcript.engine).not.toBe("fallback");
});
