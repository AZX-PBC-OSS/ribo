/**
 * @file The schema-artifact round-trip guard: the JSON Schema document the package build
 * generates (`dist/extraction.schema.json`, published at `./extraction.schema.json`) and the
 * live zod schema (`snuggExtractionSchema`) are interchangeable for everything
 * `@azx/ribo-cli`'s `inspectSchema` reports — leaf and group counts, depth, serialized size,
 * the nullable-union partition, per-group pieces, call counts, worst piece, and the canonical
 * fingerprint, compared as one deep report equality.
 *
 * NOT part of the quality-acceptance harness this directory is named for (`README.md`):
 * like the other `*.test.ts` files here it is key-free and hermetic, and runs in
 * `./check.sh`'s unit project — it reads a build artifact, no network, no backend.
 *
 * It reaches the CLI engine (`inspectSchema`) through the dev-only `@azx/ribo-cli` link —
 * the mirror image of the CLI's dev-link to this package (design §6 sanctioned the boundary;
 * ADR 0039 records the cycle). Nothing CLI-side is in the published surface.
 *
 * The artifact is build output: this test reads it with `node:fs` (a static `dist/` import
 * would fail typecheck on a clean tree, where typecheck runs before build). If it is absent,
 * the failure names the remedy.
 *
 * Must-fail mutations — each must turn this file red (design §11), on a built tree as well as
 * a clean one (the wiring test exists precisely because a leftover `dist/` would otherwise let
 * mutations 2 and 3 pass on a stale-but-plausible artifact):
 *   1. Mutate `src/schema.ts` without rebuilding — the stale artifact's bytes, report and
 *      fingerprint diverge from the live render.
 *   2. Remove the generation step from the `build` script (or delete the generator) — the
 *      wiring test fails naming the missing chain, whether or not a stale artifact is present.
 *   3. Drop `{ target: "openapi-3.0" }` from `generate-extraction-schema.mjs` — the wiring
 *      test fails on the missing literal, and a rebuilt draft-2020-12 artifact is refused by
 *      `inspectSchema` with `SchemaInspectError` (the CLI's loud draft-form refusal).
 *   4. Hand-edit `dist/extraction.schema.json` — its bytes no longer equal the live render's
 *      serialization and its report no longer equals the live schema's report.
 *   5. Remove the `./extraction.schema.json` export (either map) — the wiring test fails.
 *
 * Run on every zod bump: `z.fromJSONSchema` is marked semi-experimental upstream, and this
 * test is what proves the CLI's report path still round-trips the pinned zod's rendering
 * (see the catalog's hold comment in `pnpm-workspace.yaml` and ADR 0039).
 */

import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { inspectSchema } from "@azx/ribo-cli";
import { afterEach, expect, test } from "vitest";
import { z } from "zod";

const ARTIFACT_URL = new URL("../dist/extraction.schema.json", import.meta.url);
const GENERATOR_URL = new URL("../generate-extraction-schema.mjs", import.meta.url);
const PACKAGE_URL = new URL("../package.json", import.meta.url);
const RENDER_OPTIONS = { target: "openapi-3.0" } as const;

// The live schema, imported at runtime. Why not a static import of `../src/index.js`: this
// package typechecks as a `tsc -b` solution of two composite projects (`src` and `acceptance`),
// and a composite project may not pull its sibling's files in transitively (TS6307) — so the
// acceptance project deliberately imports nothing from `src/` at typecheck time. The runner
// resolves the specifier above; the type is sealed to `z.toJSONSchema`'s own parameter type so
// a non-schema can never reach the render call.
type RenderableSchema = Parameters<typeof z.toJSONSchema>[0];
const schemaModule = (await import("../src/index" + ".ts")) as {
  snuggExtractionSchema: RenderableSchema;
};
const snuggExtractionSchema = schemaModule.snuggExtractionSchema;

// --- The artifact's report equals the live schema's report -------------------------------

test("the generated artifact and the live schema produce the same inspect report", () => {
  if (!existsSync(fileURLToPath(ARTIFACT_URL))) {
    throw new Error(
      "dist/extraction.schema.json is missing — it is generated by the package build, not " +
        "committed. Run: pnpm --filter @azx/ribo-adapter-snuggpro build",
    );
  }
  const liveDocument = z.toJSONSchema(snuggExtractionSchema, RENDER_OPTIONS);
  const artifactBytes = readFileSync(fileURLToPath(ARTIFACT_URL), "utf8");

  // JSON.parse must succeed and inspectSchema must accept the document: the artifact is the
  // form the CLI's conversion path takes (OpenAPI 3.0 nullability, not draft-2020-12).
  const fromArtifact = inspectSchema(JSON.parse(artifactBytes));

  const fromLive = inspectSchema(liveDocument);

  // The artifact is byte-for-byte what this test's own live render serializes to — the
  // generator writes `JSON.stringify(document, null, 2) + "\\n"` of exactly this document, so
  // a hand-edited, stale, or wrongly-targeted artifact is caught even before the reports are
  // compared.
  expect(artifactBytes).toBe(`${JSON.stringify(liveDocument, null, 2)}\n`);

  // Full-report deep equality — including schemaFingerprint, which is computed over the
  // document's canonical (key-order- and whitespace-insensitive) JSON, and the generator
  // serializes exactly the live render. Every measure the task names rides in this one
  // comparison: leafCount, groupCount, whole.depth, whole.serializedChars,
  // whole.nullableUnions, pieces, calls, worstPiece.
  expect(fromArtifact).toEqual(fromLive);

  // Non-vacuity: a broken pipeline must not pass on two equal-but-empty reports.
  expect(fromLive.leafCount).toBeGreaterThan(0);
  expect(fromLive.groupCount).toBeDefined();
  expect(fromLive.groupCount).toBeGreaterThan(0);
});

// --- The build wiring and published surface are in place ----------------------------------

// This test is what makes the file fail when the feature is removed from a tree that still
// carries a leftover `dist/`: the artifact assertions above can only ever compare the artifact
// against the live schema, so they pass on any plausible artifact. The build chain, the
// generator's literal target and the export-map entries are the feature itself.
test("the build regenerates the artifact and the export map publishes it", () => {
  expect(existsSync(fileURLToPath(GENERATOR_URL))).toBe(true);
  const generator = readFileSync(fileURLToPath(GENERATOR_URL), "utf8");
  // The render call carries the literal target — the load-bearing option the CLI's
  // draft-2020-12 refusal exists for.
  expect(generator).toContain('target: "openapi-3.0"');

  const pkg = JSON.parse(readFileSync(fileURLToPath(PACKAGE_URL), "utf8")) as {
    scripts?: { build?: string };
    exports?: Record<string, string>;
    publishConfig?: { exports?: Record<string, string> };
  };
  // The generator is `&&`-chained into the build after tsdown, so a generation failure fails
  // the build and the artifact is regenerated on every build.
  const steps = (pkg.scripts?.build ?? "").split("&&").map((step) => step.trim());
  const generatorStep = steps.findIndex((step) => step.endsWith("generate-extraction-schema.mjs"));
  expect(generatorStep).toBeGreaterThan(0);
  expect(steps.slice(0, generatorStep).some((step) => step.startsWith("tsdown"))).toBe(true);

  // The subpath is published in string form, in both maps.
  expect(pkg.exports?.["./extraction.schema.json"]).toBe("./dist/extraction.schema.json");
  expect(pkg.publishConfig?.exports?.["./extraction.schema.json"]).toBe(
    "./dist/extraction.schema.json",
  );
});

// --- A refinement/transform fixture names its not-visible constructs ----------------------

const refinedAndTransformed = z.object({
  audit: z
    .object({ auditDate: z.string().refine(() => true) })
    .refine(() => true)
    .transform((value) => value),
});

let tempDir = "";

afterEach(() => {
  if (tempDir !== "") {
    rmSync(tempDir, { recursive: true, force: true });
    tempDir = "";
  }
});

test("a refinement-and-transform fixture's file round-trips with its constructs named", () => {
  // `io: "input"` is the rendering that keeps the document convertible AND walkable on the
  // pinned zod: at the output side a transform renders as an unrepresentable `{}` subtree,
  // which the leaf inventory refuses (the CLI's own findings test pins both directions).
  // The constructs cannot cross into JSON Schema either way — the report names them.
  const document = z.toJSONSchema(refinedAndTransformed, {
    target: "openapi-3.0",
    io: "input",
    unrepresentable: "any",
  });

  // A real file on real bytes, under the OS temp dir — never the repo tree.
  tempDir = mkdtempSync(join(tmpdir(), "ribo-schema-artifact-"));
  const filePath = join(tempDir, "fixture.schema.json");
  writeFileSync(filePath, JSON.stringify(document, null, 2));

  const fromMemory = inspectSchema(document);
  const fromFile = inspectSchema(JSON.parse(readFileSync(filePath, "utf8")));
  expect(fromFile).toEqual(fromMemory);

  const constructs = fromMemory.notVisible.map((row) => row.construct);
  expect(constructs).toContain("zod refinement");
  expect(constructs).toContain("zod transform");
  for (const row of fromMemory.notVisible) {
    expect(row.detail.length).toBeGreaterThan(0);
  }
});
