/**
 * The migrated Snugg corpus (`acceptance/corpus/`): the spike's real dictation transcripts
 * and their human-annotated ground truth, re-expressed in the generic corpus format
 * `@azx/ribo-cli`'s `loadCorpus` reads. The spike directory (`docs/spikes/0001-extraction-snuggpro/`)
 * is read-only to this migration and the current gate keeps running against it; this corpus is
 * what eval runs — and later the gate wrapper — measure with. `corpus/NOTES.md` records the
 * translation rules and every documented gap and narrowing.
 *
 * Hermetic and key-free: no network, no backend, no model call, no environment variables.
 * It reads two things with `node:fs`: the spike transcripts (reading the spike is the
 * established precedent — `gate.manual.ts`), and the build artifact
 * `dist/extraction.schema.json` (never committed — a missing one fails naming the remedy).
 *
 * Must-fail mutations — each must turn this file red:
 *   1. Delete or move `acceptance/corpus/` — every loading test fails.
 *   2. Mistype one leaf path in a committed `case.json` — the leaf-path test fails naming
 *      valid paths, and the loader itself refuses the corpus.
 *   3. Change one enum member in a committed `case.json` to a non-member — the membership
 *      test fails naming the leaf and its valid members.
 *   4. Edit one character of the manifest's `instructions` or `examples` — the prompt-parity
 *      test fails (the values are recomputed from the adapter's own constants, never re-typed),
 *      so a stale prompt block surfaces here rather than as a fingerprint mismatch after the
 *      paid baselines.
 *   5. Add a `fieldDescriptions` option to the gate's `singleShotExtractor` call — the
 *      text-level tripwire fails: the corpus's declared mode no longer matches the gate's.
 */

import {
  cpSync,
  existsSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { CorpusError, loadCorpus } from "@azx/ribo-cli";
import type { LoadedCorpus } from "@azx/ribo-cli";
import { isExtractedLeaf } from "@azx/ribo-core";
import { expect, test } from "vitest";

import { snuggExamples, snuggProInstructions } from "../src/index.js";

const CORPUS_URL = new URL("./corpus", import.meta.url);
const CORPUS_DIR = fileURLToPath(CORPUS_URL);
const ARTIFACT_URL = new URL("../dist/extraction.schema.json", import.meta.url);
const SPIKE_DIR = fileURLToPath(
  new URL("../../../docs/spikes/0001-extraction-snuggpro", import.meta.url),
);
const GATE_FILE = fileURLToPath(new URL("./gate.manual.ts", import.meta.url));

/** The spike's case ids, sorted — the migrated corpus's row identity. */
const spikeSlugs = readdirSync(join(SPIKE_DIR, "ground-truth"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

/**
 * Load the corpus, failing with the remedy when the schema artifact has not been built yet —
 * `./check.sh` builds before it tests, so only a bare local run sees this.
 */
const loadCorpusOrFail = (): LoadedCorpus => {
  if (!existsSync(fileURLToPath(ARTIFACT_URL))) {
    throw new Error(
      "dist/extraction.schema.json is missing — the corpus's manifest names it, and it is " +
        "generated by the package build, not committed. Run: pnpm build:packages",
    );
  }
  return loadCorpus(CORPUS_DIR);
};

/**
 * The first enum-membership fault in a loaded corpus, or `undefined` when every asserted value
 * and alternative on an enum or literal leaf is an exact member of the leaf's declared values.
 *
 * The loader refuses unknown leaf paths but deliberately does not check members (its refusal
 * lists paths only), so this walk is what keeps the corpus's vocabulary honest — and it is the
 * check the negative test below proves can actually fail.
 */
const enumMemberFault = (corpus: LoadedCorpus): string | undefined => {
  const byPath = new Map(corpus.leafInventory.map((leaf) => [leaf.path, leaf]));
  const membersOf = (value: unknown): unknown[] =>
    value !== null && typeof value === "object" ? Object.values(value) : [value];
  for (const testCase of corpus.cases) {
    for (const [path, entry] of Object.entries(testCase.expected)) {
      const leaf = byPath.get(path);
      if (leaf === undefined) {
        return (
          `the case "${testCase.id}" expects leaf "${path}", which is not a leaf of the corpus's ` +
          `schema — valid leaf paths include: ${corpus.leafInventory
            .slice(0, 5)
            .map((l) => l.path)
            .join(", ")}, …`
        );
      }
      if (entry.status !== "asserted") continue;
      if (leaf.kind !== "enum" && leaf.kind !== "literal") continue;
      const valid = leaf.values ?? [];
      for (const member of [
        ...membersOf(entry.value),
        ...(entry.alternatives ?? []).flatMap(membersOf),
      ]) {
        if (!valid.includes(member as never)) {
          return (
            `the case "${testCase.id}" asserts "${path}" with the value ${JSON.stringify(member)}, ` +
            `which is not a member of the leaf's declared values ${JSON.stringify(valid)}`
          );
        }
      }
    }
  }
  return undefined;
};

/** The example fields map the corpus format can hold, derived from the adapter's own constants. */
const deriveExampleFields = (fields: unknown): Record<string, unknown> => {
  const out: Record<string, unknown> = {};
  const walk = (node: unknown, path: string): void => {
    if (isExtractedLeaf(node)) {
      out[path] = node.value;
      return;
    }
    if (Array.isArray(node)) {
      // One array element per collection group — the runner's translation emits exactly one,
      // so the first element's leaves only, and an empty group contributes nothing.
      if (node.length > 0) walk(node[0], path);
      return;
    }
    if (node !== null && typeof node === "object") {
      for (const [key, child] of Object.entries(node)) {
        walk(child, path === "" ? key : `${path}.${key}`);
      }
    }
  };
  walk(fields, "");
  return out;
};

// --- The corpus loads through the unmodified loader -----------------------------------------

test("the migrated corpus loads through loadCorpus from @azx/ribo-cli's public entry", () => {
  const corpus = loadCorpusOrFail();
  expect(corpus.cases).toHaveLength(spikeSlugs.length);
  expect(corpus.cases.map((c) => c.id)).toEqual(spikeSlugs);
  expect(corpus.manifest.provenance).toBe("real");
  for (const testCase of corpus.cases) {
    expect(testCase.inputs).toHaveLength(1);
    expect(testCase.inputs[0]?.kind).toBe("transcript");
    expect(testCase.inputs[0]?.file).toBe("input.txt");
  }
});

test("every case's input.txt is byte-for-byte the spike transcript it migrated", () => {
  const corpus = loadCorpusOrFail();
  for (const testCase of corpus.cases) {
    const spikeBytes = readFileSync(join(SPIKE_DIR, "transcripts", `${testCase.id}.txt`));
    const migratedBytes = readFileSync(join(testCase.dir, "input.txt"));
    expect(migratedBytes.equals(spikeBytes)).toBe(true);
  }
});

test("every excluded spike instance is last in its group's list and carries no leaves", () => {
  // The migration's dense-ordinal rule renumbers current instances contiguously; that is only
  // faithful because an excluded instance sits last today. NOTES.md documents the assumption —
  // this is the assertion behind it. Reading the spike is the gate's own precedent.
  for (const slug of spikeSlugs) {
    const ground = JSON.parse(
      readFileSync(join(SPIKE_DIR, "ground-truth", `${slug}.json`), "utf8"),
    ) as { instances: Record<string, Array<{ eligibility: string; leaves?: unknown }>> };
    for (const [group, instances] of Object.entries(ground.instances)) {
      instances.forEach((instance, index) => {
        if (instance.eligibility === "current") return;
        expect(Object.keys(instance.leaves ?? {}), `${slug} ${group}[${index}]`).toEqual([]);
        expect(index, `${slug} ${group}[${index}]`).toBe(instances.length - 1);
      });
    }
  }
});

// --- The corpus's vocabulary resolves against the converted shipped schema -------------------

test("every expected leaf path and enum member resolves against the converted shipped schema", () => {
  const corpus = loadCorpusOrFail();
  expect(enumMemberFault(corpus)).toBeUndefined();
});

// --- Negative: the checks can actually fail --------------------------------------------------

/**
 * A copy of the committed corpus in a fresh temp directory, its manifest's schema reference
 * repointed (relatively) at the real artifact — a temp copy sits outside the repo, and the
 * reference is resolved against the corpus root.
 */
const copyCorpusToTemp = (): string => {
  const dir = mkdtempSync(join(tmpdir(), "snugg-corpus-"));
  cpSync(CORPUS_DIR, dir, { recursive: true });
  const manifestPath = join(dir, "manifest.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as { schema: string };
  manifest.schema = relative(dir, fileURLToPath(ARTIFACT_URL));
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
  return dir;
};

const rewriteCase = (
  dir: string,
  slug: string,
  mutate: (caseFile: Record<string, unknown>) => void,
): void => {
  const casePath = join(dir, slug, "case.json");
  const caseFile = JSON.parse(readFileSync(casePath, "utf8")) as Record<string, unknown>;
  mutate(caseFile);
  writeFileSync(casePath, JSON.stringify(caseFile, null, 2));
};

test("a leaf path that is not a leaf is refused by the loader, naming the valid paths", () => {
  const dir = copyCorpusToTemp();
  try {
    rewriteCase(dir, "01-attic-r-value-shell", (caseFile) => {
      const expected = caseFile.expected as Record<string, unknown>;
      const entry = expected["basedata.blowerDoorReading"];
      delete expected["basedata.blowerDoorReading"];
      expected["basedata.blowerDoorReadingTypo"] = entry;
    });
    const refusal = (() => {
      try {
        loadCorpus(dir);
      } catch (error) {
        return error;
      }
      throw new Error("loadCorpus succeeded on a corpus with a mistyped leaf path");
    })();
    expect(refusal).toBeInstanceOf(CorpusError);
    expect((refusal as CorpusError).message).toContain("basedata.blowerDoorReadingTypo");
    expect((refusal as CorpusError).message).toContain("basedata.blowerDoorReading");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("a non-member enum value passes the loader but fails the membership walk", () => {
  const dir = copyCorpusToTemp();
  try {
    rewriteCase(dir, "01-attic-r-value-shell", (caseFile) => {
      const expected = caseFile.expected as Record<string, unknown>;
      expected["health.healthAmbientCarbonMonoxide"] = {
        status: "asserted",
        value: "Passed Always",
        sourceSpan: "read zero",
      };
    });
    // The loader checks leaf paths only — the corpus loads.
    const corpus = loadCorpus(dir);
    const fault = enumMemberFault(corpus);
    expect(fault).toBeDefined();
    expect(fault).toContain("01-attic-r-value-shell");
    expect(fault).toContain("health.healthAmbientCarbonMonoxide");
    expect(fault).toContain("Passed Always");
    expect(fault).toContain("Passed");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

// --- The manifest's prompt inputs equal what the gate sends ---------------------------------

test("the manifest's prompt inputs are the adapter's own constants, in the mode the gate runs", () => {
  const corpus = loadCorpusOrFail();
  const prompt = corpus.manifest.prompt;

  // The instructions, character for character — the same constant the gate's fingerprint
  // hashes by source file.
  expect(prompt.instructions).toBe(snuggProInstructions);

  // The few-shot examples, derived from the adapter's constants by the corpus format's rule:
  // every leaf envelope flattened to dotted path -> value, null-valued envelopes included
  // (the honest-null lesson must survive), first array element only, empty arrays nothing.
  expect(prompt.examples).toBeDefined();
  expect(prompt.examples).toHaveLength(snuggExamples.length);
  expect(prompt.examples).toEqual(
    snuggExamples.map((example) => ({
      transcript: example.transcript,
      fields: deriveExampleFields(example.fields),
    })),
  );

  // The gate passes no fieldDescriptions option, so core's default "schema" mode is the mode
  // the gate runs under — the mode this corpus declares.
  expect(prompt.fieldDescriptions).toBe("schema");
});

test("the gate still passes no fieldDescriptions option to its extractor", () => {
  // Text-level tripwire: the day the gate gains a fieldDescriptions option, this corpus's
  // declared mode stops matching it, and the parity above would be silently stale.
  const gate = readFileSync(GATE_FILE, "utf8");
  const callStart = gate.indexOf("singleShotExtractor({");
  expect(callStart).toBeGreaterThan(0);
  const callEnd = gate.indexOf("});", callStart);
  expect(callEnd).toBeGreaterThan(callStart);
  expect(gate.slice(callStart, callEnd)).not.toContain("fieldDescriptions");
});
